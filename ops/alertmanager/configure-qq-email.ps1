[CmdletBinding()]
param(
    [string]$SenderAddress,
    [string]$RecipientAddress,
    [string]$ContainerName = "alertmanager-demo",
    [switch]$SendTest
)

$ErrorActionPreference = "Stop"

function Read-MailAddress {
    param(
        [string]$Prompt,
        [string]$Value
    )

    if ([string]::IsNullOrWhiteSpace($Value)) {
        $Value = Read-Host $Prompt
    }

    $Value = $Value.Trim()
    if ($Value -notmatch '^[^@\s]+@[^@\s]+\.[^@\s]+$') {
        throw "Invalid email address: $Value"
    }

    return $Value
}

$scriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$secretDirectory = Join-Path $scriptRoot "secrets"
$secretPath = Join-Path $secretDirectory "qq_smtp_auth_code"
$configPath = Join-Path $scriptRoot "alertmanager.yml"

$SenderAddress = Read-MailAddress -Prompt "QQ sender email" -Value $SenderAddress
$RecipientAddress = Read-MailAddress -Prompt "Alert recipient email" -Value $RecipientAddress

$secureAuthCode = Read-Host "QQ SMTP authorization code (newly generated)" -AsSecureString
$authCodePointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secureAuthCode)
try {
    $authCode = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($authCodePointer).Trim()
}
finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($authCodePointer)
}

if ([string]::IsNullOrWhiteSpace($authCode)) {
    throw "The SMTP authorization code cannot be empty."
}

New-Item -ItemType Directory -Force -Path $secretDirectory | Out-Null
$utf8WithoutBom = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText($secretPath, $authCode, $utf8WithoutBom)

try {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent().Name
    & icacls.exe $secretDirectory /inheritance:r /grant:r "${identity}:(OI)(CI)F" | Out-Null
    if ($LASTEXITCODE -ne 0) {
        Write-Warning "Could not tighten the secret directory ACL. Check the permissions manually."
    }
}
catch {
    Write-Warning "Could not tighten the secret directory ACL. Check the permissions manually."
}

$configTemplate = @'
# Generated by configure-qq-email.ps1.
# Do not put the SMTP authorization code in this file.

global:
  resolve_timeout: 5m

route:
  receiver: qq-email-warning
  group_by: ['alertname', 'severity']
  group_wait: 10s
  group_interval: 30s
  routes:
    - matchers:
        - severity="critical"
      receiver: qq-email-critical
      repeat_interval: 5m
    - matchers:
        - severity="warning"
      receiver: qq-email-warning
      repeat_interval: 15m

receivers:
  - name: qq-email-critical
    email_configs:
      - to: '__RECIPIENT__'
        from: '__SENDER__'
        smarthost: 'smtp.qq.com:465'
        auth_username: '__SENDER__'
        auth_password_file: '/etc/alertmanager/secrets/qq_smtp_auth_code'
        require_tls: true
        force_implicit_tls: true
        send_resolved: true
        headers:
          Subject: '[CRITICAL] {{ template "email.default.subject" . }}'

  - name: qq-email-warning
    email_configs:
      - to: '__RECIPIENT__'
        from: '__SENDER__'
        smarthost: 'smtp.qq.com:465'
        auth_username: '__SENDER__'
        auth_password_file: '/etc/alertmanager/secrets/qq_smtp_auth_code'
        require_tls: true
        force_implicit_tls: true
        send_resolved: true
        headers:
          Subject: '[WARNING] {{ template "email.default.subject" . }}'

inhibit_rules:
  - source_matchers:
      - alertname="NavigationMenuTargetDown"
    target_matchers:
      - alertname=~"HighServerErrorRate|HighMenuTreeLatency"
    equal: ['job', 'instance']
'@

$configText = $configTemplate.
    Replace("__SENDER__", $SenderAddress).
    Replace("__RECIPIENT__", $RecipientAddress)
[IO.File]::WriteAllText($configPath, $configText, $utf8WithoutBom)

$container = & docker ps --filter "name=^/$ContainerName$" --format "{{.Names}}"
if ($LASTEXITCODE -ne 0 -or $container -ne $ContainerName) {
    Write-Host "Configuration written to $configPath."
    Write-Host "Start the $ContainerName container, then reload Alertmanager."
    exit 0
}

& docker exec $ContainerName amtool check-config /etc/alertmanager/alertmanager.yml
if ($LASTEXITCODE -ne 0) {
    throw "Alertmanager rejected the generated configuration."
}

$reloadStatus = & curl.exe -s -o NUL -w "%{http_code}" -X POST "http://localhost:9093/-/reload"
if ($reloadStatus -ne "200") {
    throw "Alertmanager reload failed with HTTP $reloadStatus."
}

Write-Host "QQ email receiver configured and Alertmanager reloaded."

if ($SendTest) {
    & docker exec $ContainerName amtool alert add QQEmailChannelTest severity=info `
        --annotation=summary="QQ email channel test" `
        --alertmanager.url=http://localhost:9093
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to create the test alert."
    }
    Write-Host "Test alert submitted. Check the inbox after group_wait (10 seconds)."
}
